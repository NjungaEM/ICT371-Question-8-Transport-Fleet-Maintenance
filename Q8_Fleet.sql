CREATE OR REPLACE FUNCTION fn_service_due(p_vehicle_id INT)
RETURNS BOOLEAN LANGUAGE plpgsql AS $$
DECLARE v_current NUMERIC; v_service NUMERIC;
BEGIN
 SELECT current_odometer,last_service_odometer INTO v_current,v_service
 FROM vehicles WHERE vehicle_id=p_vehicle_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown vehicle'; END IF;
 RETURN v_current-v_service>=5000;
END; $$;

CREATE OR REPLACE PROCEDURE pr_record_trip(p_vehicle_id INT,p_trip_on DATE,p_start NUMERIC,p_end NUMERIC)
LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM vehicles WHERE vehicle_id=p_vehicle_id) THEN RAISE EXCEPTION 'Unknown vehicle'; END IF;
 IF p_trip_on IS NULL OR p_start IS NULL OR p_end IS NULL OR p_end<=p_start THEN
  RAISE EXCEPTION 'Invalid trip mileage or date';
 END IF;
 INSERT INTO trips(vehicle_id,trip_on,start_odometer,end_odometer)
 VALUES(p_vehicle_id,p_trip_on,p_start,p_end);
END; $$;

CREATE OR REPLACE FUNCTION trg_trip_odometer()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_current NUMERIC;
BEGIN
 SELECT current_odometer INTO v_current FROM vehicles
 WHERE vehicle_id=NEW.vehicle_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown vehicle'; END IF;
 IF NEW.start_odometer<>v_current THEN RAISE EXCEPTION 'Trip must start at current odometer'; END IF;
 IF NEW.end_odometer<=NEW.start_odometer THEN RAISE EXCEPTION 'End odometer must exceed start'; END IF;
 UPDATE vehicles SET current_odometer=NEW.end_odometer WHERE vehicle_id=NEW.vehicle_id;
 RETURN NEW;
END; $$;
CREATE TRIGGER trips_update_odometer BEFORE INSERT ON trips
FOR EACH ROW EXECUTE FUNCTION trg_trip_odometer();

CREATE VIEW v_service_due AS
SELECT registration,current_odometer-last_service_odometer AS km_since_service
FROM vehicles WHERE current_odometer-last_service_odometer>=5000;

CREATE INDEX idx_trips_vehicle_tripon ON trips(vehicle_id,trip_on);
EXPLAIN SELECT * FROM trips WHERE vehicle_id=1
AND trip_on BETWEEN DATE '2026-01-01' AND DATE '2026-01-31';

CREATE OR REPLACE PROCEDURE pr_refresh_service_alerts()
LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO service_alerts(vehicle_id,km_since_service,flagged_on)
 SELECT vehicle_id,current_odometer-last_service_odometer,CURRENT_DATE
 FROM vehicles WHERE current_odometer-last_service_odometer>=5000
 ON CONFLICT(vehicle_id) DO UPDATE SET
 km_since_service=EXCLUDED.km_since_service,flagged_on=EXCLUDED.flagged_on;
 DELETE FROM service_alerts a WHERE NOT EXISTS(
  SELECT 1 FROM vehicles v WHERE v.vehicle_id=a.vehicle_id
  AND v.current_odometer-v.last_service_odometer>=5000);
END; $$;

CREATE EXTENSION IF NOT EXISTS pg_cron;
SELECT cron.schedule('weekly-service-alerts','0 6 * * 1',
 $$CALL pr_refresh_service_alerts()$$);

